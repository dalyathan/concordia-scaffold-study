#!/usr/bin/env bash
# The frozen test2 look for Qwen 2.5 7B and Llama 3.1 8B on a fresh A40 pod (QWEN_TEST_PLAN.md, LLAMA_TEST_PLAN.md; owner go DECISIONS.md X6).
#   Tokens are read from files and never printed: /root/.hf_token (read: the artifact repo and Llama 3.1), /root/.gh_token (push to GitHub).
#   bash scripts/pod_test2_look.sh            (PIN=scorer-pin-1, TOKEN=G3-OWNER-GO:2026-11-28, MODELS="qwen25_7b llama31_8b" by default)
# Steps: repo on branch qwen with tags; the owner's pin tag must exist and the protected files must equal it; Concordia at its pinned commit;
# Python 3.11 venv with the locked versions; the frozen adapters from the private HF backup, each file's sha256 checked against
# <tag>_artifacts_manifest.json; then per model: freeze dry run, the look (scripts/test2_look.py: preflight, both splits, a commit per arm),
# the report (tools/test2_report.py), commit and push. Any failed check stops the script.
set -euo pipefail
PIN="${PIN:-scorer-pin-1}"; TOKEN="${TOKEN:-G3-OWNER-GO:2026-11-28}"; MODELS="${MODELS:-qwen25_7b llama31_8b}"
W=/workspace; mkdir -p "$W"; cd "$W"
export HF_HOME="$W/.hf_home" HF_HUB_ENABLE_HF_TRANSFER=0 HARNESS_PROVIDER=runpod
[ -s /root/.hf_token ] && [ -s /root/.gh_token ] || { echo "put the tokens in /root/.hf_token and /root/.gh_token first"; exit 1; }
HF_TOKEN="$(cat /root/.hf_token)"; export HF_TOKEN
git config --global credential.helper '!f(){ echo username=x-access-token; echo "password=$(cat /root/.gh_token)"; }; f'
git config --global user.name "Claude"; git config --global user.email "noreply@anthropic.com"

echo "== 1. repo (qwen) and the owner's pin"
[ -d concordia-scaffold-study/.git ] || git clone -q https://github.com/dalyathan/concordia-scaffold-study.git
cd concordia-scaffold-study
git fetch -q origin --tags && git checkout -q qwen && git pull -q --ff-only origin qwen
git log --oneline -1
git rev-parse -q --verify "refs/tags/$PIN" >/dev/null || { echo "the owner's pin tag $PIN does not exist on the remote"; exit 1; }

echo "== 2. concordia at the pinned commit"
C=3643ac0466f748b8055b61feb0b7908411f73d84
[ -d concordia/.git ] || git clone -q https://github.com/google-deepmind/concordia.git concordia
git -C concordia fetch -q origin "$C" 2>/dev/null || true; git -C concordia checkout -q "$C"
[ "$(git -C concordia rev-parse HEAD)" = "$C" ] || { echo "concordia pin mismatch"; exit 1; }

echo "== 3. Python 3.11 venv with the locked versions"
command -v uv >/dev/null || python3 -m pip install -q uv --break-system-packages 2>/dev/null || python3 -m pip install -q uv
[ -x .venv/bin/python ] || uv venv -q -p 3.11 .venv
uv pip install -q --python .venv/bin/python --index-strategy unsafe-best-match --extra-index-url https://download.pytorch.org/whl/cu121 -r requirements.gpu.lock
PY=.venv/bin/python
$PY - <<'PYEOF'
import torch, transformers, peft
assert torch.__version__ == "2.4.1+cu121" and transformers.__version__ == "4.44.2" and peft.__version__ == "0.12.0", (torch.__version__, transformers.__version__, peft.__version__)
assert torch.cuda.is_available() and "A40" in torch.cuda.get_device_name(0), torch.cuda.get_device_name(0)
print("torch", torch.__version__, "transformers", transformers.__version__, "peft", peft.__version__, "|", torch.cuda.get_device_name(0))
PYEOF
$PY tools/lock_protected.py --pin "$PIN"

echo "== 4. frozen adapters from the HF backup (sha256 per file)"
$PY - <<'PYEOF'
import hashlib, json, os, shutil
from huggingface_hub import hf_hub_download
for tag in ("qwen", "llama"):
  m = json.load(open(f"{tag}_artifacts_manifest.json"))
  commit = m["upload_status"].split("hub commit ")[1].split(";")[0]
  n = 0
  for f in m["files"]:
    if "adapters_harness/" not in f["local_path"] or "_last" in f["local_path"]:
      continue
    if not (os.path.exists(f["local_path"]) and hashlib.sha256(open(f["local_path"], "rb").read()).hexdigest() == f["sha256"]):
      p = hf_hub_download(m["repo"], f["repo_path"], repo_type="model", revision=commit, token=os.environ["HF_TOKEN"])
      os.makedirs(os.path.dirname(f["local_path"]), exist_ok=True); shutil.copyfile(p, f["local_path"])
    assert hashlib.sha256(open(f["local_path"], "rb").read()).hexdigest() == f["sha256"], f["local_path"]
    n += 1
  print(tag, n, "adapter files restored and sha256-checked (hub commit", commit[:8] + ")")
PYEOF
git status --porcelain | grep . && { echo "tree not clean after setup"; exit 1; } || true

for M in $MODELS; do
  echo "== 5. $M: freeze check, look, report"
  $PY scripts/test2_look.py --model "$M" --dry
  HARNESS_PIN_REF="$PIN" $PY scripts/test2_look.py --model "$M" --look --lock-token "$TOKEN"
  $PY tools/test2_report.py --model "$M"
  git add -A QWEN_TEST2_RESULTS.md LLAMA_TEST2_RESULTS.md demo_out/qwen_test2_report.json demo_out/llama_test2_report.json
  git diff --cached --quiet || git commit -q -m "test2 look $M: report generated by tools/test2_report.py from the look records"
  git push -q origin qwen
  grep -A2 "^## Conclusion" "$( [ "$M" = qwen25_7b ] && echo QWEN || echo LLAMA )_TEST2_RESULTS.md" | tail -1
done
echo "TEST2 LOOK FINISHED; records and reports pushed. SAFE TO STOP POD: yes (everything is in git; adapters are on the hub)."
