def load(path):
  d = json.load(open(path)); d["_path"] = os.path.relpath(path, ROOT); return d


def records():
  llama = [load(p) for p in sorted(glob.glob(os.path.join(ROOT, "runs", "haggling", MODEL, "*.json")))]
  ref = [load(p) for p in sorted(glob.glob(os.path.join(ROOT, "runs", "haggling", "none", "*.json")))]
  ref = [r for r in ref if (r.get("config") or {}).get("step") == "llama step 4 reference"]
  gem = {os.path.basename(p)[:-5]: load(p) for p in sorted(glob.glob(os.path.join(ROOT, "runs", "haggling", "gemma2_9b", "legacy-*.json")))}
  return llama, ref, gem


def one(recs, solver, split):
  sel = [r for r in recs if r["solver"] == solver and r["split"] == split]
  if len(sel) > 1:
    raise SystemExit(f"more than one record for {solver}/{split}: {[r['_path'] for r in sel]}")
  return sel[0] if sel else None


def rows(r):
  return [x for x in r["cases"] if not x["planted"]]


def soft(x): return max(x["payoffs"]) - float(np.dot(x["payoffs"], x["probs"]))


def hard(x):
  p = x["probs"]; top = max(range(len(p)), key=lambda i: (p[i], -i)); return max(x["payoffs"]) - x["payoffs"][top]


def group(x): return (x["inputs"]["V"], x["inputs"]["grid_name"])


class Arm:
  """Per-case values of one arm on one split; several records (seeds) are averaged per case."""
  def __init__(self, recs, label):
    assert recs, label
    self.label, self.recs = label, recs
    ids = [sorted(x["cid"] for x in rows(r)) for r in recs]
    assert all(i == ids[0] for i in ids), f"{label}: seeds cover different cases"
    by = [{x["cid"]: x for x in rows(r)} for r in recs]
    self.cids = ids[0]
    self.case = {c: by[0][c] for c in self.cids}
    self.soft = {c: float(np.mean([soft(b[c]) for b in by])) for c in self.cids}
    self.hard = {c: float(np.mean([hard(b[c]) for b in by])) for c in self.cids}
    self.offer = {c: float(np.mean([np.dot(b[c]["probs"], b[c]["inputs"]["grid"]) for b in by])) for c in self.cids}
    self.seed_soft = [float(np.mean([soft(x) for x in rows(r)])) for r in recs]

  def mean(self, typ=None, metric="soft"):
    d = getattr(self, metric)
    v = [d[c] for c in self.cids if typ is None or self.case[c]["type"] == typ]
    return float(np.mean(v))


_RNG_CACHE = {}


def boot_idx(groups):
  key = tuple(groups)
  if key not in _RNG_CACHE:
    rng = np.random.Generator(np.random.PCG64(0))
    _RNG_CACHE[key] = rng.integers(0, len(groups), size=(B, len(groups)))
  return _RNG_CACHE[key]


def ci_mean(values_by_cid, cases, typ=None):
  """cluster bootstrap 95% interval of the mean over cases (optionally of one type)."""
  cids = sorted(c for c in values_by_cid if typ is None or cases[c]["type"] == typ)
  gs = sorted({group(cases[c]) for c in cids})
  S = np.array([sum(values_by_cid[c] for c in cids if group(cases[c]) == g) for g in gs])
  N = np.array([sum(1 for c in cids if group(cases[c]) == g) for g in gs])
  idx = boot_idx(gs)
  stats = S[idx].sum(1) / N[idx].sum(1)
  return float(np.mean([values_by_cid[c] for c in cids])), float(np.percentile(stats, 2.5)), float(np.percentile(stats, 97.5))


def diff(a, b, typ=None):
  assert a.cids == b.cids, f"{a.label} vs {b.label}: different cases"
  return ci_mean({c: a.soft[c] - b.soft[c] for c in a.cids}, a.case, typ)


def perm_p(a, b):
  """two-sided sign-flip permutation p-value of the paired mean difference, flipping (V, grid) groups (10,000 flips, PCG64 seed 0)."""
  d = {c: a.soft[c] - b.soft[c] for c in a.cids}
  gs = sorted({group(a.case[c]) for c in a.cids})
  S = np.array([sum(d[c] for c in a.cids if group(a.case[c]) == g) for g in gs]); n = len(a.cids)
  obs = abs(S.sum() / n)
  rng = np.random.Generator(np.random.PCG64(0))
  flips = rng.choice([-1.0, 1.0], size=(B, len(gs)))
  return float((np.abs((flips * S).sum(1) / n) >= obs - 1e-12).mean())


def slope(arm):
  cids = [c for c in arm.cids if arm.case[c]["type"] == "below"]
  x = np.array([arm.case[c]["inputs"]["C"] for c in cids], float); y = np.array([arm.offer[c] for c in cids])
  gs = sorted({group(arm.case[c]) for c in cids}); gi = np.array([gs.index(group(arm.case[c])) for c in cids])
  point = float(np.polyfit(x, y, 1)[0])
  rng = np.random.Generator(np.random.PCG64(0)); st = []
  for _ in range(2000):                          # 2,000 resamples for the slope (a least-squares fit per resample)
    pick = rng.integers(0, len(gs), len(gs))
    m = np.concatenate([np.where(gi == g)[0] for g in pick])
    if len(set(x[m])) >= 2:
      st.append(np.polyfit(x[m], y[m], 1)[0])
  return point, float(np.percentile(st, 2.5)), float(np.percentile(st, 97.5))


def mass(recs):
  m = [v for r in recs for x in rows(r) for v in (x["letter_mass"] or []) if v is not None]
  return (float(np.mean(m)), float(np.min(m))) if m else (None, None)


def position_bias(recs):
  vecs = [[po[ORDERS[k][j]] for j in range(5)] for r in recs for x in rows(r) if x.get("per_order_probs") for k, po in enumerate(x["per_order_probs"])]
  if not vecs:
    return None, None
  v = np.mean(vecs, 0); return float(v.max()), "abcde"[int(v.argmax())]


def planted(recs):
  return f"{sum(r['planted']['n_ok'] for r in recs)}/{sum(r['planted']['n'] for r in recs)}"


def gpu(recs):
  return sum((r.get("timing") or {}).get("gpu_seconds") or 0 for r in recs)


f3 = lambda v: "-" if v is None else f"{v:.3f}"
fci = lambda t: f"{t[0]:.3f} [{t[1]:.3f}, {t[2]:.3f}]"


