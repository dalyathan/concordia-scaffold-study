def g2_checks(arms, gem, J):
  """Checks added after review gate G2 (CPU, from the same records; descriptive, no decision rule depends on them)."""
  P, U, W = arms.get(("plain", "tune")), arms.get(("uniform", "tune")), arms.get(("notes:wrong_rule", "tune"))
  out = ["### Checks added after review gate G2 (descriptive; from the same records)" if MODEL == "llama31_8b" else
         "### Checks from the Llama G2 review, built into this plan (descriptive; from the same records)", ""]
  if P and U:
    out += ["**Plain against uniform guessing** (plain minus uniform; negative = plain better):", "",
            "| type | plain | uniform | plain minus uniform [95%] |", "| --- | --- | --- | --- |"]
    for t in (None,) + TYPES:
      d = diff(P, U, t); J[f"diff/tune/plain_minus_uniform/{t or 'all'}"] = d
      out.append(f"| {t or 'all'} | {P.mean(t):.3f} | {U.mean(t):.3f} | {fci(d)} |")
    out.append("")
  if W:
    out += ["**Paragraphs against the wrong rule** (arm minus wrong rule):", "", "| arm | minus wrong rule [95%] (perm. p) |", "| --- | --- |"]
    for n in ("method_original", "teacher"):
      a = arms.get((f"notes:{n}", "tune"))
      if a:
        d = diff(a, W); pp = perm_p(a, W); J[f"diff/tune/notes:{n}_minus_wrong_rule"] = {"ci": d, "perm_p": pp}
        out.append(f"| {NOTE_LABEL[n]} | {fci(d)} (p {pp:.3f}) |")
    out.append("")
  out += ["**Signed offer error** per type: the expected offer (probability-weighted price) minus the nearest payoff-optimal price, "
          "0 inside the optimal range; positive = offers too much. Mean over the tune cells.", "",
          "| arm | all | below | at or above | no cost | top letter share |", "| --- | --- | --- | --- | --- | --- |"]
  rowsg = [("uniform", U)] + [(lab, arms.get((sv, "tune"))) for sv, lab in [("plain", f"plain {NAME}")] + [(f"notes:{n}", NOTE_LABEL[n]) for n in NOTES]]
  if "legacy-plain-tune-s0" in gem:
    rowsg.append(("plain Gemma (imported record; confounded)", Arm([gem["legacy-plain-tune-s0"]], "gemma plain")))
  for lab, a in rowsg:
    if a is None:
      continue
    v = {t: float(np.mean([a.signed[c] for c in a.cids if t is None or a.case[c]["type"] == t])) for t in (None,) + TYPES}
    pb = position_bias(a.recs)[0] if lab != "uniform" else 0.2
    J[f"signed_error/{lab}"] = {(t or "all"): x for t, x in v.items()} | {"top_letter_share": pb}
    out.append(f"| {lab} | " + " | ".join(f"{v[t]:+.2f}" for t in (None,) + TYPES) + f" | {f3(pb)} |")
  return out + [""]


def build():
  llama, ref, gem = records()
  out, J = [], {"limitation": LIMITATION}
  out += readout_checks(J)
  cfg = lambda r: r.get("config") or {}
  # ---------------- references and step 4
  refs = {"oracle": "oracle", "uniform": "uniform", "baseline:cheapest": "always-cheapest", "baseline:stated_cost_rule": "stated-cost rule"}
  step4 = [("plain", "plain")] + [(f"notes:{n}", NOTE_LABEL[n]) for n in NOTES]
  out += [f"## Step 4: plain {NAME}, references and prompt arms", "",
          f"Train and tune cells only. One record per arm and split; soft regret in coins with 95% cluster-bootstrap intervals over (V, grid) groups. "
          f"Code check: {LIMITATION}.", ""]
  arms = {}
  tune_ref = one(ref, "oracle", "tune")
  if tune_ref:
    ng = len({group(x) for x in rows(tune_ref)}); J["tune_groups"] = ng
    out += [f"Tune has {len({x['inputs']['cell'] for x in rows(tune_ref)})} cells in {ng} (V, grid) groups (the bootstrap clusters; with this few groups percentile intervals undercover).", ""]
  for split in ("tune", "train"):
    out += [f"### {split}", "", "| arm | n cases | soft regret [95%] | below | at or above | no cost | hard regret | slope on stated cost [95%] | letter mass mean / min | top letter share | planted |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for solver, label in list(refs.items()) + step4:
      r = one(ref if solver in refs else llama, solver, split)
      if r is None:
        out.append(f"| {label} | not run | | | | | | | | | |"); continue
      a = Arm([r], label); arms[(solver, split)] = a
      sl = slope(a) if solver not in ("oracle",) else None
      mm, mn = mass([r]) if solver not in refs else (None, None)
