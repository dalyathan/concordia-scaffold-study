#!/usr/bin/env python3
"""Generate RESULTS_GENERATED.md from run records only (no hand-typed numbers). Every number is recomputed from the per-case rows.
  python tools/make_report.py            writes the file
  python tools/make_report.py --check    exit 1 if the file on disk differs from what the records give"""
import collections, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "RESULTS_GENERATED.md")


def load():
  out = []
  for dp, _, fs in os.walk(os.path.join(ROOT, "runs")):
    for f in sorted(fs):
      if f.endswith(".json"):
        r = json.load(open(os.path.join(dp, f))); r["_path"] = os.path.relpath(os.path.join(dp, f), ROOT); out.append(r)
  return sorted(out, key=lambda r: r["_path"])


def metric(rec):
  rows = [x for x in rec["cases"] if not x["planted"]]
  return sum(x["score"]["soft_regret"] for x in rows) / len(rows), len(rows)


def build() -> str:
  groups = collections.defaultdict(list)
  for r in load():
    groups[(r["task"], r["model"], r["split"], r["solver"])].append(r)
  lines = ["# Generated results", "",
           "Generated by `python tools/make_report.py` from the run records in `runs/`; do not edit by hand "
           "(`tests/harness/test_report_fresh.py` fails if this file is stale). Mean soft regret in coins per decision, lower is better, "
           "averaged over the records (seeds) listed. Planted known-answer cases are reported in their own column, never in the mean.", "",
           "| task | model | split | solver | seeds | n cases | soft regret (mean of seeds) | per seed | planted ok | GPU h | approx USD | records |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
  for (task, model, split, solver), rs in sorted(groups.items(), key=lambda kv: tuple(str(x) for x in kv[0])):
    vals = [metric(r)[0] for r in rs]
    n = metric(rs[0])[1]
    pl = [r["planted"] for r in rs]
    planted = "n/a" if all(p["n"] == 0 for p in pl) else f"{sum(p['n_ok'] for p in pl)}/{sum(p['n'] for p in pl)}"
    gh = [r["timing"].get("gpu_seconds") for r in rs]; usd = [r["timing"].get("approx_usd") for r in rs]
    gpu = f"{sum(gh) / 3600:.2f}" if all(g is not None for g in gh) else "n/a"
    cost = f"{sum(usd):.2f}" if all(u is not None for u in usd) else "n/a"
    lines.append(f"| {task} | {model} | {split} | {solver} | {len(rs)} | {n} | {sum(vals) / len(vals):.3f} | "
                 f"{', '.join(f'{v:.3f}' for v in vals)} | {planted} | {gpu} | {cost} | {len(rs)} |")
  lines += ["", "## By case type (mean of seeds)", "", "| task | split | solver | type | n | soft regret |", "| --- | --- | --- | --- | --- | --- |"]
  for (task, model, split, solver), rs in sorted(groups.items(), key=lambda kv: tuple(str(x) for x in kv[0])):
    bt = collections.defaultdict(list)
    for r in rs:
      for typ in {x["type"] for x in r["cases"] if not x["planted"]}:
        xs = [x["score"]["soft_regret"] for x in r["cases"] if not x["planted"] and x["type"] == typ]
        bt[typ].append((sum(xs) / len(xs), len(xs)))
    for typ, v in sorted(bt.items()):
      lines.append(f"| {task} | {split} | {solver} | {typ} | {v[0][1]} | {sum(a for a, _ in v) / len(v):.3f} |")
  return "\n".join(lines) + "\n"


if __name__ == "__main__":
  text = build()
  if "--check" in sys.argv:
    sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 1)
  open(OUT, "w").write(text); print("wrote", OUT, len(text.splitlines()), "lines")
