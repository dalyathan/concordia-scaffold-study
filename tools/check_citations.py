#!/usr/bin/env python3
"""Citation check: find every arXiv id cited in the repo's markdown files, look each one up on arxiv.org (abs page and export API),
and compare the title and first author with what the citing line says.

  python tools/check_citations.py [--md CITATION_CHECKS.md]

For RELATED_SETUPS.md the expected (first author, short title) is parsed from the citation line `**Surname et al., "Title".**`.
For other files an id with no parsable citation is only checked for existence and listed as UNCHECKED-CONTEXT.
A lookup that fails (network blocked, HTTP error) is reported as NOT VERIFIED, never as ok. Nothing is guessed."""
import argparse, glob, os, re, sys, time, urllib.request, xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ID = re.compile(r"arxiv\.org/abs/(\d{4}\.\d{4,5})(?:v\d+)?")
CITE = re.compile(r'\*\*([A-Z][^*]*?)(?: et al\.?| and [A-Z]\w+)?,\s*"([^"]+)"')
NS = {"a": "http://www.w3.org/2005/Atom"}


def lookup(aid):
  url = f"https://export.arxiv.org/api/query?id_list={aid}"
  with urllib.request.urlopen(url, timeout=30) as r:
    root = ET.fromstring(r.read())
  e = root.find("a:entry", NS)
  if e is None or e.find("a:title", NS) is None or "Error" in (e.findtext("a:title", "", NS)):
    return None
  authors = [x.findtext("a:name", "", NS) for x in e.findall("a:author", NS)]
  return {"title": " ".join(e.findtext("a:title", "", NS).split()), "authors": authors,
          "published": e.findtext("a:published", "", NS)[:10]}


def norm(s): return re.sub(r"[^a-z0-9 ]", "", s.lower())


def find_citations():
  out = {}
  for f in sorted(glob.glob(os.path.join(ROOT, "*.md"))):
    lines = open(f).read().splitlines()
    for i, l in enumerate(lines):
      for aid in ID.findall(l):
        # the citing line is the nearest bullet above (or this line) holding a **Author, "Title"** pattern
        exp = None
        for j in range(i, max(i - 6, -1), -1):
          m = CITE.search(lines[j])
          if m:
            exp = (m.group(1).strip(), m.group(2).strip()); break
        out.setdefault(aid, []).append((os.path.basename(f), i + 1, exp))
  return out


def main():
  ap = argparse.ArgumentParser(); ap.add_argument("--md", default=os.path.join(ROOT, "CITATION_CHECKS.md")); a = ap.parse_args()
  cites = find_citations()
  rows, bad = [], 0
  for aid, where in sorted(cites.items()):
    f, ln, exp = where[0]
    try:
      info = lookup(aid); time.sleep(3)
    except Exception as e:
      rows.append((aid, f"{f}:{ln}", "NOT VERIFIED", f"lookup failed: {type(e).__name__}: {str(e)[:80]}", exp)); bad += 1; continue
    if info is None:
      rows.append((aid, f"{f}:{ln}", "NOT FOUND", "arXiv has no entry for this id", exp)); bad += 1; continue
    detail = f"{info['authors'][0]} et al. ({len(info['authors'])} authors), {info['published']}: {info['title']}"
    if exp is None:
      rows.append((aid, f"{f}:{ln}", "UNCHECKED-CONTEXT", detail, exp)); continue
    first_ok = norm(exp[0].split()[-1]) in norm(info["authors"][0])
    words = [w for w in norm(exp[1]).split() if len(w) > 3]
    title_ok = sum(w in norm(info["title"]) for w in words) >= max(1, int(0.6 * len(words)))
    status = "OK" if first_ok and title_ok else "MISMATCH"
    bad += status != "OK"
    rows.append((aid, f"{f}:{ln}", status, detail, exp))
  L = ["# CITATION_CHECKS", "", "Generated by `python tools/check_citations.py`; each id is looked up on arxiv.org. Do not edit by hand.", "",
       f"{len(rows)} ids; {sum(r[2] == 'OK' for r in rows)} OK; {bad} not OK.", "",
       "| arXiv id | cited at | status | what arXiv says | what the citing line says |", "| --- | --- | --- | --- | --- |"]
  for aid, at, st, det, exp in rows:
    L.append(f"| {aid} | {at} | {st} | {det} | {exp[0] + ': ' + exp[1] if exp else '-'} |")
  open(a.md, "w").write("\n".join(L) + "\n")
  print("\n".join(f"{r[0]} {r[2]}" for r in rows))
  return 1 if bad else 0


if __name__ == "__main__":
  sys.exit(main())
